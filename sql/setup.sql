DROP TABLE IF EXISTS Shapes;
DROP TABLE IF EXISTS RoundRecord;

CREATE TABLE Shapes (
	id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image       TEXT NOT NULL,
    sharpness   DECIMAL(4, 3) NOT NULL CHECK(sharpness >= 0 and sharpness <= 1),
    curviness   DECIMAL(4, 3) NOT NULL CHECK(curviness >= 0 and curviness <= 1),
    confusion   DECIMAL(4, 3) NOT NULL CHECK(confusion >= 0 and confusion <= 1),
    precision   DECIMAL(4, 3) NOT NULL CHECK(precision >= 0 and precision <= 1)
);

CREATE TABLE RoundRecord (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shape_id    INTEGER NOT NULL REFERENCES Shapes(id),
    accuracy    DECIMAL(4, 3) NOT NULL CHECK(accuracy >= 0 and accuracy <= 1),
    time        DECIMAL(5, 2) NOT NULL CHECK(time >= 0 and time <= 600),
    username    TEXT NOT NULL,
    score       DECIMAL(6, 2) NOT NULL
);

